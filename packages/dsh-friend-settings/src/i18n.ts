export function t(
  key: I18nKey,
  language: FriendUiLanguage | 'zh' | 'en',
  systemLanguage?: string,
): string {
  const resolved = language === 'zh' || language === 'en'
    ? language
    : resolveUiLanguage(language, systemLanguage)
  return EN[key] === undefined && ZH[key] === undefined
    ? key
    : (resolved === 'en' ? EN[key] : ZH[key]) ?? ZH[key] ?? key
}

export function missingI18nKeys(): { zh: I18nKey[]; en: I18nKey[] } {
  const zh: I18nKey[] = []
  const en: I18nKey[] = []
  for (const key of I18N_KEYS) {
    if (ZH[key] === undefined) zh.push(key)
    if (EN[key] === undefined) en.push(key)
  }
  return { zh, en }
}
